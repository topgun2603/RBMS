/** Variants of one option: [value, price ₹, MRP ₹, stock]. */
function one(option: string, rows: [string, number, number, number][]): Pick<DemoProduct, "options" | "variants"> {
  return {
    options: [{ name: option, values: rows.map((r) => r[0]) }],
    variants: rows.map(([value, price, mrp, stock]) => ({ values: { [option]: value }, price: rs(price), mrp: rs(mrp), stock })),
  };
}

/** Variants of two options (every colour in every size): prices per size, stock per pair. */
function two(a: string, as: string[], b: string, bs: [string, number, number][], stock: number): Pick<DemoProduct, "options" | "variants"> {
  const variants: DemoVariant[] = [];
  for (const x of as) for (const [y, price, mrp] of bs) variants.push({ values: { [a]: x, [b]: y }, price: rs(price), mrp: rs(mrp), stock });
  return { options: [{ name: a, values: as }, { name: b, values: bs.map((r) => r[0]) }], variants };
}

