type Row = [string, number, number, number];

/** Variants of one option: [value, price ₹, MRP ₹, stock]. */
function one(option: string, rows: Row[]): Pick<DemoProduct, "options" | "variants"> {
  return {
    options: [{ name: option, values: rows.map((r) => r[0]) }],
    variants: rows.map(([value, price, mrp, stock]) => ({ values: { [option]: value }, price: rs(price), mrp: rs(mrp), stock })),
  };
}

/** Two options where the price follows the second (the pack): every `a` value × [b value, price ₹, MRP ₹]. */
function packs(a: [string, string[]], b: [string, [string, number, number][]], stock: (x: string, y: string) => number): Pick<DemoProduct, "options" | "variants"> {
  return {
    options: [
      { name: a[0], values: a[1] },
      { name: b[0], values: b[1].map((r) => r[0]) },
    ],
    variants: a[1].flatMap((x) => b[1].map(([y, price, mrp]) => ({ values: { [a[0]]: x, [b[0]]: y }, price: rs(price), mrp: rs(mrp), stock: stock(x, y) }))),
  };
}

