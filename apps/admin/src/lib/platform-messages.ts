export const platformMessages = { en, ta } as const;

export function platformTranslator(locale: Locale | string): Translator {
  return createTranslator(locale === "ta" ? platformMessages.ta : platformMessages.en, platformMessages.en, locale);
}

/** Nav labels without a hook (the dashboard layout already has the locale). */
export const platformNavLabels = (locale: Locale | string) => {
  const t = platformTranslator(locale);
  return { risk: t("admin.pt.nav.risk"), support: t("admin.pt.nav.support"), news: t("admin.pt.nav.news") };
};

export function usePlatformT(): Translator {
  const { locale } = useI18n();
  return React.useMemo(() => platformTranslator(locale), [locale]);
}
