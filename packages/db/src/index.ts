import { drizzle, type PostgresJsDatabase } from "drizzle-orm/postgres-js";
import { timestamp, uuid } from "drizzle-orm/pg-core";
import postgres from "postgres";

/** Schema-agnostic handle; modules import their own tables and query through it. */
export type Db = PostgresJsDatabase<Record<string, unknown>>;
/** A transaction handle, accepted anywhere a Db is. */
export type Tx = Parameters<Parameters<Db["transaction"]>[0]>[0];
export type DbOrTx = Db | Tx;

export function createDb(url: string, opts: { max?: number } = {}) {
  const client = postgres(url, { max: opts.max ?? 10 });
  const db: Db = drizzle(client);
  return { db, close: () => client.end() };
}

/** Primary key column: random UUID generated by Postgres. */
export const pk = () => uuid("id").primaryKey().defaultRandom();

/** Owning tenant. Every tenant-scoped table has this column and filters on it in every query. */
export const tenantId = () => uuid("tenant_id").notNull();

export const timestamps = () => ({
  createdAt: timestamp("created_at", { withTimezone: true }).notNull().defaultNow(),
  updatedAt: timestamp("updated_at", { withTimezone: true })
    .notNull()
    .defaultNow()
    .$onUpdate(() => new Date()),
});

/**
 * The few query helpers the API host (apps/api) needs for its own small cross-module lookups, re-exported so the host
 * doesn't take a direct drizzle-orm dependency. Packages import drizzle-orm themselves.
 */
export { and, eq, gt, inArray, isNotNull, isNull, like, lt, or, sql, type SQL } from "drizzle-orm";

