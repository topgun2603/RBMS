export function packFor(type: string | null | undefined): BusinessPack | null {
  const k = (type ?? "").trim().toLowerCase().replace(/[\s-]+/g, "_");
  if (!k) return null;
  if ((BUSINESS_TYPES as readonly string[]).includes(k)) return PACKS[k as BusinessType];
  const alias = ALIASES[k];
  return alias ? PACKS[alias] : null;
}

/** The catch-all packs of batch 8: a trade without a pack of its own lands on the one for its app. */
export const GENERAL_PACKS = ["general_shop", "general_counter", "general_services"] as const satisfies readonly BusinessType[];

export const isGeneralPack = (type: string | null | undefined): boolean => (GENERAL_PACKS as readonly string[]).includes(type ?? "");

/** The pack a shop of this app gets when it never chose a business type (or typed one we don't cover). */
export const DEFAULT_PACK_FOR_APP: Record<AppId, BusinessType> = {
  BL: "general_counter",
  EC: "general_shop",
  PH: "pharmacy",
  RS: "restaurant",
  SV: "general_services",
  SC: "school",
};

export function packOrDefault(type: string | null | undefined, appId: string | null | undefined): BusinessPack {
  return packFor(type) ?? PACKS[DEFAULT_PACK_FOR_APP[(appId as AppId) ?? "EC"] ?? "general_shop"];
}

/**
 * The pack for a shop: its chosen pack id first, then whatever the owner typed (`businessLabel`, resolved through the
 * aliases), then the app's default (a general pack for EC / BL / SV).
 */
export function resolvePack(type: string | null | undefined, label: string | null | undefined, appId: string | null | undefined): BusinessPack {
  return packFor(type) ?? packFor(label) ?? packOrDefault(null, appId);
}

/** Packs grouped for a picker, in `PACK_GROUPS` order (empty groups left out); the order within a group follows `BUSINESS_TYPES`. */
export function packsByGroup(filter?: (p: BusinessPack) => boolean): { group: PackGroup; packs: BusinessPack[] }[] {
  return PACK_GROUPS.map((group) => ({ group, packs: BUSINESS_TYPES.map((id) => PACKS[id]).filter((p) => p.group === group && (!filter || filter(p))) })).filter((g) => g.packs.length > 0);
}

/** A group of the trade picker (the shape `TradePicker` in @rbms/ui takes). */
export interface PackPickerGroup {
  key: PackGroup;
  label: string;
  options: { value: BusinessType; label: string; hint: string; keywords: string }[];
}

/**
 * The trade picker's groups for a locale: every real trade under its heading (the general packs are what "Not listed" falls
 * back to, so they are not listed). Within a group, trades made for `appId` come first. Search matches both languages.
 */
export function packPickerGroups(locale: string | null | undefined, appId?: string | null): PackPickerGroup[] {
  const ta = locale === "ta";
  return packsByGroup((p) => !isGeneralPack(p.id)).map(({ group, packs }) => ({
    key: group,
    label: PACK_GROUP_NAMES[group][ta ? "ta" : "en"],
    options: [...packs]
      .sort((a, b) => Number(b.appId === appId) - Number(a.appId === appId))
      .map((p) => ({ value: p.id, label: ta ? p.nameTa : p.name, hint: p.tagline, keywords: `${p.name} ${p.nameTa} ${p.id.replace(/_/g, " ")}` })),
  }));
}

/** The pack's words for a locale (Tamil falls back to English). */
export const copyFor = (pack: BusinessPack, locale: string | null | undefined): Copy => (locale === "ta" ? pack.copy.ta : pack.copy.en);
