import { qrmpOn, compositionOn, type GstConfig } from "./config";
import { addDays, addMonths, daysBetween, fyStartYear, monthRange, quarterOfMonth } from "./util";

/**
 * Due dates of the returns, as notified (not shifted for public holidays or extensions announced later):
 * - GSTR-1 monthly: 11th of the next month; quarterly (QRMP): 13th after the quarter (Rule 59(1)).
 * - GSTR-3B monthly: 20th of the next month; QRMP: 22nd (Category X States and UTs) or 24th (the others) after the quarter
 *   (Notification 14/2020-CT and later).
 * - PMT-06 (QRMP monthly payment): 25th of the next month, for the first two months of the quarter.
 * - CMP-08: 18th after the quarter (Rule 62(1)). GSTR-4: 30 April after the year (Rule 62(1) as amended).
 * - GSTR-2B: generated by the portal on the 14th of the next month (nothing to file).
 */

export type ReturnKind = "gstr1" | "gstr3b" | "pmt06" | "cmp08" | "gstr4" | "gstr2b";

/** State codes of Category X (return due the 22nd under QRMP): the others get the 24th. */
const CATEGORY_X = new Set(["22", "23", "24", "25", "26", "27", "29", "30", "31", "32", "33", "34", "35", "36", "37"]);

export interface DueItem {
  returnType: ReturnKind;
  /** "YYYY-MM" or "YYYY-Qn" or "FY2026-27". */
  period: string;
  /** What the return covers, for display: the month or quarter start and end. */
  from: string;
  to: string;
  dueDate: string;
  filed: boolean;
  filedOn: string | null;
  /** Days to the due date (negative = late), null when filed. */
  daysLeft: number | null;
  status: "filed" | "overdue" | "due_soon" | "upcoming";
}

const nextMonth = (month: string, day: number) => `${addMonths(month, 1)}-${String(day).padStart(2, "0")}`;

export interface FilingMark {
  returnType: string;
  period: string;
  filedOn: string;
}

/**
 * The returns that fall due around `today`: everything due from two months back to a month ahead, with filed marks.
 * Composition shops get CMP-08 and GSTR-4, not GSTR-1 and 3B.
 */
export function filingCalendar(today: string, config: GstConfig, stateCode: string | null, filings: readonly FilingMark[]): DueItem[] {
  const items: DueItem[] = [];
  const done = new Map(filings.map((f) => [`${f.returnType}|${f.period}`, f.filedOn]));
  const make = (returnType: ReturnKind, period: string, from: string, to: string, dueDate: string): DueItem => {
    const filedOn = done.get(`${returnType}|${period}`) ?? null;
    const daysLeft = filedOn ? null : daysBetween(today, dueDate);
    const status: DueItem["status"] = filedOn ? "filed" : daysLeft! < 0 ? "overdue" : daysLeft! <= 7 ? "due_soon" : "upcoming";
    return { returnType, period, from, to, dueDate, filed: !!filedOn, filedOn, daysLeft, status };
  };
  const thisMonth = today.slice(0, 7);
  // Only returns that fell due in the last two months or fall due soon: older ones are history, not a to-do list.
  const inWindow = (due: string) => due >= `${addMonths(thisMonth, -2)}-01` && due <= `${addMonths(thisMonth, 2)}-01`;

  // Months whose returns fall due in the window: the period ended in [-4, +0] months.
  for (let back = 0; back <= 4; back++) {
    const month = addMonths(thisMonth, -back);
    const r = monthRange(month);
    const comp = compositionOn(config, r.to);
    const qrmp = qrmpOn(config, month);
    const q = quarterOfMonth(month);
    const isQuarterEnd = month === q.months[2];
    if (comp) {
      if (isQuarterEnd) {
        const due = nextMonth(month, 18);
        if (inWindow(due)) items.push(make("cmp08", q.key, q.from, q.to, due));
      }
      if (month === `${fyStartYear(`${month}-01`) + 1}-03`) {
        const fy = fyStartYear(`${month}-01`);
        const due = `${fy + 1}-04-30`;
        if (inWindow(due) || due >= `${thisMonth}-01`) items.push(make("gstr4", `FY${fy}-${String((fy + 1) % 100).padStart(2, "0")}`, `${fy}-04-01`, `${fy + 1}-03-31`, due));
      }
      continue;
    }
    if (qrmp) {
      if (isQuarterEnd) {
        const day3b = stateCode && CATEGORY_X.has(stateCode) ? 22 : 24;
        const d1 = nextMonth(month, 13);
        const d3 = nextMonth(month, day3b);
        if (inWindow(d1)) items.push(make("gstr1", q.key, q.from, q.to, d1));
        if (inWindow(d3)) items.push(make("gstr3b", q.key, q.from, q.to, d3));
      } else {
        const pmt = nextMonth(month, 25);
        if (inWindow(pmt)) items.push(make("pmt06", month, r.from, r.to, pmt));
      }
    } else {
      const d1 = nextMonth(month, 11);
      const d3 = nextMonth(month, 20);
      if (inWindow(d1)) items.push(make("gstr1", month, r.from, r.to, d1));
      if (inWindow(d3)) items.push(make("gstr3b", month, r.from, r.to, d3));
    }
    const d2b = nextMonth(month, 14);
    if (!comp && inWindow(d2b) && d2b >= addDays(today, -3)) items.push(make("gstr2b", month, r.from, r.to, d2b));
  }
  return items.sort((a, b) => a.dueDate.localeCompare(b.dueDate) || a.returnType.localeCompare(b.returnType));
}
