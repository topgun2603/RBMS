export function labels(locale: DocLocale): Labels {
  return locale === "ta" ? ta : en;
}

export const normalizeLocale = (value: string | null | undefined): "en" | "ta" =>
  value?.toLowerCase().startsWith("ta") ? "ta" : "en";
