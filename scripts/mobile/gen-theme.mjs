#!/usr/bin/env node
// Generates dart/srikit_theme/lib/src/srikit_defaults.dart from the platform default brand tokens in
// packages/branding/src/tokens.ts (`DEFAULT_BRAND_TOKENS`), so the app's pre-shop theme matches the web.
//
//   node scripts/mobile/gen-theme.mjs           write the file
//   node scripts/mobile/gen-theme.mjs --check   exit 1 when the file is out of date (for CI)
//
// No dependencies: the object literal is read with regular expressions. Only the fields the mobile theme uses are
// read (colors, radius, fontSans, fontHeading, mode); the storefront `theme` block is web-only. If tokens.ts changes
// shape so that parsing fails, the script stops with an error instead of guessing.

import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "../..");
const src = resolve(root, "packages/branding/src/tokens.ts");
const out = resolve(root, "dart/srikit_theme/lib/src/srikit_defaults.dart");

const text = readFileSync(src, "utf8");
const block = text.match(/export const DEFAULT_BRAND_TOKENS\s*:\s*BrandTokens\s*=\s*\{([\s\S]*?)\n\};/);
if (!block) fail("DEFAULT_BRAND_TOKENS not found");
const body = block[1];

const colorsBody = body.match(/colors\s*:\s*\{([^}]*)\}/)?.[1];
if (colorsBody === undefined) fail("DEFAULT_BRAND_TOKENS.colors not found");
const colors = {};
for (const m of colorsBody.matchAll(/(\w+)\s*:\s*"(#[0-9a-fA-F]{6})"/g)) colors[m[1]] = m[2].toLowerCase();
if (!colors.primary) fail("DEFAULT_BRAND_TOKENS.colors.primary not found");

const num = (key) => {
  const m = body.match(new RegExp(`\\b${key}\\s*:\\s*([0-9.]+)`));
  return m ? Number(m[1]) : undefined;
};
const str = (key) => body.match(new RegExp(`\\b${key}\\s*:\\s*"([^"]*)"`))?.[1];

// Schema defaults from brandTokensSchema (used when the defaults object omits a field).
const tokens = {
  colors,
  radius: num("radius") ?? 0.625,
  fontSans: str("fontSans") ?? "Inter",
  fontHeading: str("fontHeading"),
  mode: str("mode") ?? "light",
};
if (!["light", "dark", "system"].includes(tokens.mode)) fail(`unknown mode "${tokens.mode}"`);

const dartStr = (v) => (`'${v.replace(/\\/g, "\\\\").replace(/'/g, "\\'")}'`);
const colorKeys = ["primary", "secondary", "accent", "background", "foreground"];
const dart = `// GENERATED by scripts/mobile/gen-theme.mjs from packages/branding/src/tokens.ts. Do not edit.
// Run \`node scripts/mobile/gen-theme.mjs\` after changing DEFAULT_BRAND_TOKENS.

import 'brand_tokens.dart';

/// The platform default brand tokens (\`DEFAULT_BRAND_TOKENS\`), used before a shop is chosen.
const srikitDefaultTokens = BrandTokens(
  colors: BrandColors(
${colorKeys.filter((k) => colors[k]).map((k) => `    ${k}: ${dartStr(colors[k])},`).join("\n")}
  ),
  radius: ${Number.isInteger(tokens.radius) ? tokens.radius.toFixed(1) : tokens.radius},
  fontSans: ${dartStr(tokens.fontSans)},
${tokens.fontHeading === undefined ? "" : `  fontHeading: ${dartStr(tokens.fontHeading)},\n`}  mode: BrandMode.${tokens.mode},
);
`;

if (process.argv.includes("--check")) {
  let current = "";
  try {
    current = readFileSync(out, "utf8");
  } catch {}
  if (current.replace(/\r\n/g, "\n") !== dart) {
    console.error(`${out} is out of date; run node scripts/mobile/gen-theme.mjs`);
    process.exit(1);
  }
  console.log("srikit_defaults.dart is up to date");
} else {
  writeFileSync(out, dart);
  console.log(`wrote ${out}`, tokens);
}

function fail(msg) {
  console.error(`gen-theme: ${msg} in ${src}`);
  process.exit(1);
}
